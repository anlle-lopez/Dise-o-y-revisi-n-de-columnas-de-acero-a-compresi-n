    pts.append((t + R, t))
    for i in range(n + 1):
        a = -math.pi / 2 - (math.pi / 2) * i / n
        pts.append((t + R + R * math.cos(a), t + R + R * math.sin(a)))
    pts.append((t, b - r1))
    for i in range(n + 1):
        a = (math.pi / 2) * i / n
        pts.append((t - r1 + r1 * math.cos(a), b - r1 + r1 * math.sin(a)))
    pts.append((0.0, b))
    P_ = np.array(pts)
    x, y = P_[:, 0], P_[:, 1]
    x1, y1 = np.roll(x, -1), np.roll(y, -1)
    cr = x * y1 - x1 * y
    A = cr.sum() / 2.0
    cx = ((x + x1) * cr).sum() / (6 * A)
    cy = ((y + y1) * cr).sum() / (6 * A)
    Ixx = ((y * y + y * y1 + y1 * y1) * cr).sum() / 12 - A * cy * cy
    Iyy = ((x * x + x * x1 + x1 * x1) * cr).sum() / 12 - A * cx * cx
    Ixy = ((x * y1 + 2 * x * y + 2 * x1 * y1 + x1 * y) * cr).sum() / 24 - A * cx * cy
    Ip = (Ixx + Iyy) / 2.0
    Rr = math.sqrt(((Ixx - Iyy) / 2.0) ** 2 + Ixy ** 2)
    return dict(A=A, xb=cx, Ix=Ixx, Iy=Iyy, Imax=Ip + Rr, Imin=Ip - Rr, rz=math.sqrt((Ip - Rr) / A))


