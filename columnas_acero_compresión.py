def k_eurocodigo(psiA, psiB, desplazable=True):
    """K según formulación tipo Eurocódigo / AISC (Dumonteil)."""
    if desplazable:
        num = 1.6 * psiA * psiB + 4.0 * (psiA + psiB) + 7.5
        den = psiA + psiB + 7.5
        return math.sqrt(num / den)
    num = 3.0 * psiA * psiB + 1.4 * (psiA + psiB) + 0.64
    den = 3.0 * psiA * psiB + 2.0 * (psiA + psiB) + 1.28
    return num / den


def k_nsr10(GA, GB):
    """K de pórtico NO arriostrado (NSR-10 / AISC): resuelve la ecuación de la hoja
    (GA*GB*(pi/K)^2 - 36)/(6(GA+GB)) - (pi/K)/tan(pi/K) = 0 por bisección."""
    GA = max(float(GA), 0.0)
    GB = max(float(GB), 0.0)
    if GA + GB < 1e-12:
        return 1.0

    def f(x):
        return (GA * GB * x * x - 36.0) / (6.0 * (GA + GB)) - x / math.tan(x)

    lo, hi = 1e-6, PI - 1e-9  # f(lo) < 0 < f(hi)
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if f(mid) < 0.0:
            lo = mid
        else:
            hi = mid
    return PI / (0.5 * (lo + hi))


